def fail(core, message):
    raise core.InvalidBundle(message)


def checked(core, function, *args, **kwargs):
    """Report shared-library errors through the CLI's ordinary error path."""
    try:
        return function(*args, **kwargs)
    except L.BundleError as exc:
        raise core.InvalidBundle(str(exc)) from None


def stage_path(value, core):
    path = Path(os.path.abspath(value))
    core.require(path.is_dir() and not path.is_symlink() and path.resolve() == path,
                 f'Stage must be an existing directory without symlinks: {path}')
    return path


def load_stage(value, core):
    root = stage_path(value, core)
    file = root / 'STAGE.json'
    core.require(file.is_file() and not file.is_symlink(), f'Not a lepton-customize stage (no STAGE.json): {root}')
    try:
        state = json.loads(core.read_small(file), object_pairs_hook=core.unique_keys)
    except ValueError:
        fail(core, f'Invalid STAGE.json in {root}')
    core.require(isinstance(state, dict) and type(state.get('format_version')) is int and
                 state['format_version'] == 1 and state.get('state') in STATES and
                 type(state.get('sysbake_required')) is bool, f'Unsupported STAGE.json in {root}')
    core.require(state['sysbake_required'] == (state['state'] in ('prepared', 'customized')),
                 'Inconsistent STAGE.json: sysbake_required does not match the stage state')
    return root, state


def write_stage(root, state):
    temporary = root / f'.STAGE.json.{os.getpid()}.tmp'
    with temporary.open('x') as stream:
        stream.write(json.dumps(state, indent=2) + '\n')
        stream.flush()
        os.fsync(stream.fileno())
    os.replace(temporary, root / 'STAGE.json')


def regular(root, name, core):
    path = root / name
    for parent in Path(name).parents:
        if str(parent) != '.':
            core.require(not (root / parent).is_symlink(), f'Unexpected symlink in stage: {parent}')
    core.require(path.is_file() and not path.is_symlink(), f'Missing stage file: {name}')
    return path


def expected_components(state, core):
    if state['state'] == 'prepared' or state.get('baked_from') == 'prepared':
        return dict.fromkeys(L.COMPONENTS, False)
    components = state.get('components')
    core.require(isinstance(components, dict) and all(type(components.get(n, False)) is bool for n in L.COMPONENTS),
                 'STAGE.json lacks valid component flags')
    return {name: components.get(name, False) for name in L.COMPONENTS}


# ---------------------------------------------------------------- ADB
def adb_pins(root, core):
    text = regular(root, INSTALLER, core).read_text(errors='replace')
    pins = {}
    for key, pattern in (('ADB_URL', r'https://dl\.google\.com/android/repository/platform-tools_[A-Za-z0-9._-]+-linux\.zip'),
                         ('ADB_SHA256', r'[0-9a-f]{64}'), ('ADB_VERSION', r'[0-9][0-9A-Za-z.-]*')):
        match = re.search(rf"^{key}='({pattern})'$", text, re.M)
        core.require(match, f'Bundled installer lacks a valid {key} pin')
        pins[key] = match[1]
    return pins


class HttpsOnly(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        if not newurl.startswith('https://'):
            raise urllib.error.URLError(f'refusing non-HTTPS redirect to {newurl}')
        return super().redirect_request(req, fp, code, msg, headers, newurl)


def download(url, destination, core, limit=256 * 1024 * 1024):
    core.require(url.startswith('https://dl.google.com/'), f'Unexpected download URL: {url}')
    opener = urllib.request.build_opener(HttpsOnly)
    request = urllib.request.Request(url, headers={'User-Agent': 'lepton-customize'})
    try:
        with opener.open(request, timeout=60) as response, destination.open('xb') as output:
            total = 0
            for chunk in iter(lambda: response.read(1024 * 1024), b''):
                total += len(chunk)
                core.require(total <= limit, 'Download is unexpectedly large')
                output.write(chunk)
    except (urllib.error.URLError, OSError) as exc:
        fail(core, f'Could not download Platform-Tools from Google ({exc}); nothing was changed. '
                   'Offline: --adb-zip FILE with the same official ZIP.')


def zip_member(archive, name, core, limit=64 * 1024 * 1024):
    try:
        with zipfile.ZipFile(archive) as z:
            member = z.getinfo(name)
            core.require(not member.is_dir() and member.file_size <= limit, f'Unexpected ZIP entry: {name}')
            return z.read(member)
    except KeyError:
        fail(core, f'Platform-Tools ZIP lacks {name}')
    except zipfile.BadZipFile:
        fail(core, f'Not a valid ZIP file: {archive}')


def adb_verified(path, pins, core, run=True):
    if hashlib.sha256(path.read_bytes()).hexdigest() != pins['ADB_SHA256']:
        return False
    if not run:
        return True
    try:
        result = subprocess.run([str(path), 'version'], capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.TimeoutExpired):
        return False
    return result.returncode == 0 and f'Version {pins["ADB_VERSION"]}' in result.stdout


def adb_main(args, core):
    root, _ = load_stage(args.stage_dir, core)
    pins = adb_pins(root, core)
    target = root / 'tools/platform-tools'
    adb = target / 'adb'
    if target.exists() or target.is_symlink():
        core.require(adb.is_file() and not adb.is_symlink() and not target.is_symlink() and
                     adb_verified(adb, pins, core), f'Existing staged adb is not the pinned version; refusing overwrite: {adb}')
        print(f'PASS: pinned Google adb {pins["ADB_VERSION"]} already staged (stage-only; never packaged)')
        return
    zip_path = None
    if args.adb_zip:
        zip_path = Path(os.path.abspath(args.adb_zip))
        core.require(zip_path.is_file(), f'ADB ZIP not found: {zip_path}')
        if args.check:
            core.require(hashlib.sha256(zip_member(zip_path, 'platform-tools/adb', core)).hexdigest() == pins['ADB_SHA256'],
                         'The ZIP adb does not match the pinned SHA256')
    if args.check:
        print(f'PASS: ADB preflight; would install pinned adb {pins["ADB_VERSION"]} from ' +
              (str(zip_path) if zip_path else pins['ADB_URL']) + '; nothing changed')
        return
    work = Path(tempfile.mkdtemp(prefix='.lepton-adb-', dir=root / 'tools'))
    try:
        if zip_path is None:
            print(f'Downloading {pins["ADB_URL"]} (official Google Platform-Tools)', flush=True)
            zip_path = work / 'platform-tools.zip'
            download(pins['ADB_URL'], zip_path, core)
        out = work / 'platform-tools'
        out.mkdir()
        (out / 'adb').write_bytes(zip_member(zip_path, 'platform-tools/adb', core))
        os.chmod(out / 'adb', 0o755)
        notice = zip_member(zip_path, 'platform-tools/NOTICE.txt', core)
        core.require(adb_verified(out / 'adb', pins, core),
                     f'adb does not match the pinned SHA256 {pins["ADB_SHA256"]} and version {pins["ADB_VERSION"]}; nothing changed')
        (out / 'SOURCE.txt').write_text(
            'Google Android Platform-Tools adb for local stage testing only.\n'
            'lepton-customize package never includes it; installers download it themselves.\n'
            f'Source: {pins["ADB_URL"] if zip_path.parent == work else "local copy of " + pins["ADB_URL"]}\n'
            f'Version: {pins["ADB_VERSION"]}\nadb SHA256 (verified): {pins["ADB_SHA256"]}\n')
        licenses = root / 'tools/licenses'
        licenses.mkdir(exist_ok=True)
        notice_path = licenses / 'google-platform-tools-NOTICE.txt'
        if not notice_path.exists():
            (work / 'NOTICE.txt').write_bytes(notice)
            core.publish(work / 'NOTICE.txt', notice_path)
        core.publish(out, target)
    finally:
        core.cleanup(work)
    print(f'PASS: pinned Google adb {pins["ADB_VERSION"]} staged at {adb} (stage-only; never packaged)')


# ---------------------------------------------------------------- sysbake
def host_problems(rendering, stage=None):
    problems = []
    selinux = selinux_problem(stage)
    if selinux:
        problems.append(selinux)
    for program, (fedora, ubuntu) in SYSBAKE_COMMANDS.items():
        if not shutil.which(program):
            problems.append(f'Missing host command: {program} (Fedora: dnf install {fedora}; Ubuntu: apt install {ubuntu})')
    filesystems = os.environ.get('LEPTON_HOST_FILESYSTEMS', '/proc/filesystems')
    try:
        binder = any(line.split()[-1:] == ['binder'] for line in Path(filesystems).read_text().splitlines())
    except OSError:
        binder = False
    if not binder:
        problems.append('Android Binder (BinderFS) kernel support is not available. It comes from the kernel '
                        '(binder_linux, rust_binder or built in); lepton-customize never loads kernel modules.')
    if shutil.which('systemctl'):
        try:
            result = subprocess.run(['systemctl', '--user', 'is-system-running'], capture_output=True,
                                    text=True, timeout=20)
            session = result.stdout.strip()
        except (OSError, subprocess.TimeoutExpired):
            session = 'unavailable'
        if session not in ('running', 'degraded'):
            problems.append(f'A systemd user session is required (systemctl --user is-system-running: {session or "no answer"}). '
                            'Log in normally (not with su/sudo), or enable lingering: loginctl enable-linger')
    problems += rootless_problems()
    runtime = os.environ.get('XDG_RUNTIME_DIR', f'/run/user/{os.getuid()}')
    if not (runtime.startswith('/run/user/') and os.path.isdir(runtime) and os.stat(runtime).st_uid == os.getuid()):
        problems.append(f'User runtime directory unavailable or unexpected: {runtime}')
    if rendering not in ('software', 'amd'):
        problems.append(f'Unknown rendering mode: {rendering}')
    return problems


def subordinate_ids(kind):
    """True when the user has a subordinate UID ('u') or GID ('g') range."""
    import pwd
    user = pwd.getpwuid(os.getuid()).pw_name
    override = os.environ.get('LEPTON_HOST_SUBUID' if kind == 'u' else 'LEPTON_HOST_SUBGID')
    if not override and shutil.which('getsubids'):
        # Also covers ranges from SSSD/LDAP rather than /etc/subuid.
        result = subprocess.run(['getsubids', *(['-g'] if kind == 'g' else []), user],
                                capture_output=True, text=True)
        return result.returncode == 0 and bool(result.stdout.strip())
    try:
        lines = Path(override or ('/etc/subuid' if kind == 'u' else '/etc/subgid')).read_text().splitlines()
    except OSError:
        return False
    return any(line.split(':')[0] in (user, str(os.getuid())) and len(line.split(':')) == 3 for line in lines)


def rootless_problems():
    """Rootless Podman prerequisites that otherwise fail late, inside sysbake."""
    problems = []
    for kind, label in (('u', 'UID'), ('g', 'GID')):
        if not subordinate_ids(kind):
            problems.append(f'No subordinate {label} range for this user (rootless Podman needs one). Add one with: '
                            'sudo usermod --add-subuids 100000-165535 --add-subgids 100000-165535 "$USER"')
    if not Path(os.environ.get('LEPTON_HOST_FUSE', '/dev/fuse')).exists():
        problems.append('/dev/fuse is missing (fuse-overlayfs needs the fuse kernel module)')
    try:
        namespaces = int(Path(os.environ.get('LEPTON_HOST_USERNS', '/proc/sys/user/max_user_namespaces')).read_text())
    except (OSError, ValueError):
        namespaces = None
    if namespaces == 0:
        problems.append('User namespaces are disabled (user.max_user_namespaces=0); rootless Podman cannot run')
    return problems


SELINUX_POLICY = 'tools/customize/selinux/lepton_binder.te'
BINDER_PERMISSIONS = ('call', 'transfer', 'set_context_mgr', 'impersonate')


def selinux_binder_allowed(selinuxfs=None):
    """Whether SELinux lets Lepton's container (spc_t, label=disable) use Binder.

    Asks the kernel through selinuxfs 'access', as libselinux does, so no root
    is needed. Returns None when SELinux is absent, permissive or unanswerable.
    """
    root = Path(selinuxfs or os.environ.get('LEPTON_HOST_SELINUXFS', '/sys/fs/selinux'))
    try:
        if (root / 'enforce').read_text().strip() != '1':
            return None
        klass = int((root / 'class/binder/index').read_text())
        bits = [int((root / 'class/binder/perms' / name).read_text()) for name in BINDER_PERMISSIONS]
        user_role = Path('/proc/self/attr/current').read_text().strip('\0\n ').split(':')[:2]
        context = ':'.join((user_role if len(user_role) == 2 else ['system_u', 'system_r']) + ['spc_t', 's0'])
        allowed = selinux_allowed_vector(root, context, klass)
    except (OSError, ValueError, IndexError):
        return None
    return all(allowed & (1 << (bit - 1)) for bit in bits)


def selinux_allowed_vector(root, context, klass):
    """The kernel's allowed-permission vector for context -> context:klass."""
    fd = os.open(root / 'access', os.O_RDWR)
    try:
        os.write(fd, f'{context} {context} {klass}'.encode())
        return int(os.read(fd, 256).decode().split()[0], 16)
    finally:
        os.close(fd)


def selinux_problem(stage=None):
    if selinux_binder_allowed() is not False:
        return None
    policy = Path(stage) / SELINUX_POLICY if stage else None
    if policy and policy.is_file():
        source, write = str(policy), ''
    else:  # Bundles made before the policy was shipped: the same three lines.
        source = '/tmp/lepton_binder.te'
        write = ("    printf '%s\\n' 'module lepton_binder 1.2;' "
                 "'require { type spc_t; class binder { call transfer set_context_mgr impersonate }; }' "
                 "'allow spc_t self:binder { call transfer set_context_mgr impersonate };' > /tmp/lepton_binder.te\n")
    return ('SELinux (enforcing) denies Binder to the Android container: binder { set_context_mgr } for spc_t, '
            'so Android cannot boot. Install Lepton\'s policy module once (keeps SELinux enforcing; Fedora: '
            'sudo dnf install checkpolicy semodule-utils):\n' + write +
            f'    checkmodule -M -m -o /tmp/lepton_binder.mod {source}\n'
            '    semodule_package -o /tmp/lepton_binder.pp -m /tmp/lepton_binder.mod\n'
            '    sudo semodule -i /tmp/lepton_binder.pp')


def quarantine(root):
    """Move an unvalidated sysbake aside; it is never left as stage state."""
    tool = root / 'compat_tool'
    leftovers = [p for p in (tool / 'sysbake', tool / 'sysbake.xattrs') if p.exists() or p.is_symlink()]
    if not leftovers:
        return None
    holder = Path(tempfile.mkdtemp(prefix='.sysbake-rejected-', dir=root))
    for path in leftovers:
        path.rename(holder / path.name)
    return holder


def validate_sysbake(root, state, core):
    tool = root / 'compat_tool'
    baked = tool / 'sysbake'
    core.require(baked.is_dir() and not baked.is_symlink(), 'Sysbake produced no directory')
    packages = regular(root, L.SYSBAKE + 'system/packages.xml', core).read_bytes()
    components = expected_components(state, core)
    names = checked(core, L.check_registered_packages, packages, components['gapps'])
    print(f'PASS: baked packages.xml registers {len(names)} packages', flush=True)
    for name in ('misc/ethernet/ipconfig.txt', 'misc/apexdata/com.android.tethering/misc/ethernet/ipconfig.txt',
                 'lepton-onboot', 'lepton-on-app-exit'):
        core.require(not (baked / name).exists(), f'Unexpected host state baked into Android data: {name}')
    sockets = []
    records = checked(core, L.scan_directory, baked, sockets)
    entries = checked(core, L.parse_xattrs, regular(root, L.XATTRS, core).read_bytes())
    unarchived = checked(core, L.check_xattr_paths, entries, records)
    core.require(set(unarchived) <= {'sysbake/' + name for name in sockets},
                 'sysbake.xattrs names files that are missing from sysbake')
    return records


def sysbake_main(args, core):
    root, state = load_stage(args.stage_dir, core)
    if state['state'] == 'restored-complete':
        fail(core, 'This restored complete stage keeps its original validated sysbake; package it directly. '
                   'To change Android, create a new prepared stage from the base bundle (which discards sysbake).')
    if state['state'] == 'baked':
        fail(core, 'This stage already has a fresh validated sysbake; package it. An existing sysbake is never overwritten.')
    tool = root / 'compat_tool'
    for path in (tool / 'sysbake', tool / 'sysbake.xattrs'):
        core.require(not path.exists() and not path.is_symlink(),
                     f'Existing sysbake present: refusing overwrite ({path}). Move it aside; STAGE.json says it is not validated.')
    script = regular(root, SYSBAKE_SCRIPT, core)
    problems = host_problems(args.rendering, root)
    if problems:
        fail(core, 'Sysbake host requirements are not met; nothing was changed:\n  ' + '\n  '.join(problems))
    rootfs = root / L.ROOTFS
    print('Recording the Android rootfs (content, types, permissions, links)...', flush=True)
    before = checked(core, L.scan_directory, rootfs)
    rootfs_digest = L.tree_digest(before)
    recorded = (state.get('android') or {}).get('rootfs_tree_sha256')
    core.require(recorded in (None, rootfs_digest),
                 'The Android rootfs changed after this stage was created or customised; create a new stage')
    inject = runpy.run_path(str(HERE / 'lepton_customize_inject.py'))
    base = ['bash', script, '--stage-dir', root, '--rendering', args.rendering]
    inject['command'](base[:2] + ['--check'] + base[2:], core)
    if args.check:
        print('PASS: sysbake preflight (host, stage and bundled helper); nothing changed')
        return
    work_before = set(root.glob('.sysbake-work.*'))
    try:
        inject['command'](base[:2] + ['--execute', '--timeout', str(args.timeout)] + base[2:], core)
        baked_records = validate_sysbake(root, state, core)
        after = checked(core, L.scan_directory, rootfs)
        core.require(L.tree_digest(after) == rootfs_digest, 'The Android rootfs changed during sysbake')
    except BaseException as exc:
        holder = quarantine(root)
        work = sorted(set(root.glob('.sysbake-work.*')) - work_before)
        detail = ''.join(f'\n  diagnostics: {path}' for path in work)
        if holder:
            detail += f'\n  unvalidated output moved aside: {holder}'
        if isinstance(exc, core.InvalidBundle):
            raise core.InvalidBundle(f'{exc}\nSysbake failed; STAGE.json is unchanged and still requires sysbake.' + detail) from None
        raise
    xattrs = regular(root, L.XATTRS, core)
    previous = state['state']
    state.update(state='baked', baked_from=previous, sysbake_required=False,
                 android=dict(rootfs_tree_sha256=rootfs_digest),
                 sysbake=dict(origin='generated', generator='lepton-customize sysbake', rendering=args.rendering,
                              created=time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()),
                              tree_sha256=L.tree_digest(baked_records),
                              xattrs_sha256=L.file_sha256(xattrs)),
                 runtime_fingerprint=L.stage_fingerprint(root)['fingerprint'])
    write_stage(root, state)
    for work in sorted(set(root.glob('.sysbake-work.*')) - work_before):
        # Logs and the run's (tiny) private Podman store; Android-owned files
        # inside need the user namespace to delete.
        print(f'Sysbake logs kept (never packaged): {work}\n  remove when no longer needed: podman unshare rm -rf {work}')
    print(f'PASS: fresh sysbake validated and recorded in {root / "STAGE.json"}\nNext: lepton-customize package')


# ---------------------------------------------------------------- package
def packaged(name, core):
    """Distributable stage entries (relative stage path)."""
    if name in GENERATED or name in ('STAGE.json',) or name.startswith('source-bundle'):
        return False
    if name in ('compat_tool/sysbake', L.XATTRS) or name.startswith(L.SYSBAKE):
        return not any(p.startswith(('.runtime-profile', '__pycache__')) for p in name.split('/'))
    return core.retained(name)


PRIVATE_NAMES = {'.git', '.ssh', '.aws', '__pycache__', 'podman-storage', 'compatdata', 'lepton-apkm',
                 'app_overlay', 'data_overlay'}
PRIVATE_PREFIXES = ('.runtime-profile', '.sysbake-', '.lepton-', '.STAGE.json')


def stage_entries(root, generated, core):
    """Packaged stage paths, parents first.

    Each file is decided on its own path; a directory is packaged when it is
    itself distributable or holds something that is (e.g. tests/runtime).
    Android sockets are never archived, as with GNU tar. Private and work
    areas are not entered; any other unreadable directory is an error.
    """
    def failed(error):
        raise core.InvalidBundle(f'Cannot read stage directory {error.filename}: {error.strerror}')
    included = set()
    for parent, dirs, files in os.walk(root, onerror=failed, followlinks=False):
        relative = Path(parent).relative_to(root).as_posix()
        prefix = '' if relative == '.' else relative + '/'
        dirs[:] = sorted(d for d in dirs if d not in PRIVATE_NAMES and not d.startswith(PRIVATE_PREFIXES)
                         and not (prefix == '' and d == 'source-bundle'))
        for item in dirs:
            if packaged(prefix + item, core):
                included.add(prefix + item)
        for item in files:
            name = prefix + item
            if name in generated or not packaged(name, core):
                continue
            info = (root / name).lstat()
            if stat.S_ISSOCK(info.st_mode) and name.startswith(L.SYSBAKE):
                continue
            core.require(stat.S_ISREG(info.st_mode) or stat.S_ISLNK(info.st_mode), f'Unsupported stage entry: {name}')
            included.add(name)
    for name in list(included):
        included.update(parent.as_posix() for parent in Path(name).parents if str(parent) != '.')
    return sorted(included)


def safe_id(value, pattern, label, core, limit):
    core.require(isinstance(value, str) and len(value) <= limit and re.fullmatch(pattern, value), f'Invalid {label}: {value!r}')
    return value


def check_stage_for_package(root, state, core):
    for name in PACKAGE_REQUIRED:
        core.require(regular(root, name, core).stat().st_size > 0, f'Empty stage file: {name}')
    for name in PACKAGE_EXECUTABLES:
        core.require((root / name).stat().st_mode & 0o111, f'Executable bit missing: {name}')
    core.require(b'/lepton-x86_64-entry %verb%' in (root / 'compat_tool/toolmanifest.vdf').read_bytes(),
                 'Steam toolmanifest.vdf does not start lepton-x86_64-entry')
    core.require(b'binderfs-ensure' in (root / L.ROOTFS / 'system/etc/init/hw/init.rc').read_bytes(),
                 'Android init.rc lacks the BinderFS helper hook')
    core.require(re.search(rb"^DEFAULT_ARCHIVE=''$", (root / INSTALLER).read_bytes(), re.M),
                 'Bundled installer template marker missing')
    for directory in ('compat_tool', 'compat_tool/liblepton', 'compat_tool/tools'):
        for path in sorted((root / directory).iterdir()):
            if path.is_file() and not path.is_symlink():
                head = path.read_bytes()[:64]
                if path.suffix == '.sh' or head.startswith((b'#!/bin/bash', b'#!/usr/bin/env bash')):
                    result = subprocess.run(['bash', '-n', str(path)], capture_output=True, text=True)
                    core.require(result.returncode == 0, f'Shell syntax error in {path}: {result.stderr.strip()}')
                elif path.suffix == '.py' or head.startswith(b'#!/usr/bin/env python3'):
                    try:
                        ast.parse(path.read_text(encoding='utf-8'))
                    except (SyntaxError, UnicodeDecodeError) as exc:
                        fail(core, f'Python syntax error in {path}: {exc}')
    shim = root / 'compat_tool/liblepton/ndk_auxv/bin/liblepton_ndk_auxv.so'
    validator = root / 'compat_tool/liblepton/ndk_auxv/validate.sh'
    if shim.is_file() and validator.is_file():
        result = subprocess.run(['bash', str(validator), str(shim)], capture_output=True, text=True)
        core.require(result.returncode == 0, 'Bundled NDK shim failed validation: ' + (result.stderr or result.stdout).strip())


def verify_manifest(rootfs, manifest, core):
    for line in manifest.read_text().splitlines():
        match = re.fullmatch(r'([0-9a-f]{64}) [ *](?:\./)?(.+)', line)
        core.require(match, f'Malformed provenance manifest: {manifest}')
        file = rootfs / match[2]
        core.require(file.resolve() == file and file.is_file() and L.file_sha256(file) == match[1],
                     f'Component file differs from its provenance record: {match[2]}')


def check_components(root, state, core):
    rootfs = root / L.ROOTFS
    actual = checked(core, L.stage_components, rootfs)
    expected = expected_components(state, core)
    for name in L.COMPONENTS:
        core.require(actual[name] == expected[name],
                     f'Rootfs {name} presence ({actual[name]}) does not match the stage record ({expected[name]})')
    bridge = core.properties((rootfs / 'system/build.prop').read_bytes()).get('ro.dalvik.vm.native.bridge')
    core.require(bridge == ('libndk_translation.so' if actual['ndk'] else '0'),
                 f'Native bridge property {bridge!r} does not match NDK presence')
    for name, folder in (('ndk', 'compat_tool/ndk-provenance'), ('gapps', 'compat_tool/provenance/gapps'),
                         ('widevine', 'compat_tool/provenance/widevine')):
        manifest = root / folder / 'SHA256SUMS'
        if actual[name] and manifest.is_file():
            verify_manifest(rootfs, manifest, core)
    library = root / 'tools/customize/lib/google-services.sh'
    if actual['gapps'] and library.is_file():
        result = subprocess.run(['bash', '-c', 'source "$1"; google_services_framework_check "$2"', 'check',
                                 str(library), str(rootfs / 'system/framework/services.jar')], capture_output=True, text=True)
        core.require(result.returncode == 0, 'services.jar lacks the Lepton GApps framework modifications')
    return actual


def stage_integrity(root, state, core):
    """Android rootfs, sysbake and xattrs must be exactly what was baked/restored."""
    rootfs = checked(core, L.scan_directory, root / L.ROOTFS)
    baked = checked(core, L.scan_directory, root / L.SYSBAKE, [])
    xattrs = regular(root, L.XATTRS, core)
    entries = checked(core, L.parse_xattrs, xattrs.read_bytes())
    unarchived = checked(core, L.check_xattr_paths, entries, baked)
    if unarchived:
        print(f'NOTE: sysbake.xattrs records {len(unarchived)} path(s) that are not archived '
              '(Android sockets; tar never stores them): ' + ', '.join(unarchived[:5]))
    android, sysbake = state.get('android') or {}, state.get('sysbake') or {}
    core.require(android.get('rootfs_tree_sha256') == L.tree_digest(rootfs),
                 'The Android rootfs differs from the one this sysbake belongs to. Modified Android needs a new '
                 'prepared/customised stage and a fresh sysbake.')
    core.require(sysbake.get('tree_sha256') == L.tree_digest(baked), 'compat_tool/sysbake changed after it was validated')
    core.require(sysbake.get('xattrs_sha256') == L.file_sha256(xattrs), 'sysbake.xattrs changed after it was validated')
    return rootfs, baked


def source_identity(root, core):
    folder = root / 'source-bundle'
    files = {}
    for path in sorted(folder.iterdir()) if folder.is_dir() else ():
        core.require(path.is_file() and not path.is_symlink(), f'Unexpected source provenance entry: {path}')
        files[path.name] = core.read_small(path)
    core.require('BUNDLE.json' in files and 'SOURCE.json' in files, 'Stage lacks source-bundle provenance')
    metadata = json.loads(files['BUNDLE.json'], object_pairs_hook=core.unique_keys)
    source = json.loads(files['SOURCE.json'], object_pairs_hook=core.unique_keys)
    core.require(isinstance(metadata, dict) and isinstance(source, dict), 'Invalid source-bundle provenance')
    return metadata, source, files


def provenance_text(args, state, metadata, source, components, digests, original):
    customized = state['state'] == 'baked' and state.get('baked_from') == 'customized'
    lines = [
        'Packaging: lepton-customize package (local customised bundle; NOT an official Lepton release)',
        'Packaged without a source checkout, compilation or Android rebuild',
        f'Bundle ID: {args.bundle_id}', f'Tool ID: {args.tool_id}',
        f'Source bundle: {metadata.get("bundle_id")} ({source.get("archive")}, SHA256 {source.get("sha256")}, '
        f'publisher signature {"verified" if source.get("authenticated") else "NOT verified"})',
        f'Stage type: {state["state"]}' + (f' (from {state["baked_from"]})' if state.get('baked_from') else ''),
        'Components: ' + ', '.join(f'{n}={str(components[n]).lower()}' for n in L.COMPONENTS),
    ]
    commit = re.search(r'^Launcher source commit: ([0-9a-f]{40})$', original, re.M)
    if commit:
        lines.append(f'Original launcher source commit (source bundle): {commit[1]}')
    if customized:
        lines.append('Android artifacts: base image from the source bundle (tools/BASE-IMAGE-PROVENANCE.txt), '
                     'modified afterwards by lepton-customize inject; not compiled from a new source checkout')
    else:
        lines.append('Android artifacts: unchanged from the source bundle (tools/IMAGE-PROVENANCE.txt)')
    sysbake = state['sysbake']
    if sysbake.get('origin') == 'generated':
        lines.append(f'Sysbake: generated locally by lepton-customize sysbake ({sysbake.get("rendering")} rendering)')
    else:
        lines.append('Sysbake: retained unchanged from the source bundle')
    lines += [f'Rootfs tree SHA256: {digests[0]}', f'Sysbake tree SHA256: {digests[1]}',
              f'sysbake.xattrs SHA256: {digests[2]}', f'Runtime fingerprint: {digests[3]}',
              f'Source provenance: compat_tool/provenance/sources/{metadata.get("bundle_id")}/',
              'Payload provenance: compat_tool/provenance and compat_tool/ndk-provenance when present',
              'Google Android Platform-Tools adb: NOT included in this archive']
    return '\n'.join(lines) + '\n'


def package_main(args, core):
    root, state = load_stage(args.stage_dir, core)
    if state['state'] in ('prepared', 'customized'):
        fail(core, 'This stage has no validated sysbake yet; run: lepton-customize sysbake --execute --stage-dir ' + str(root))
    core.require(isinstance(state.get('sysbake'), dict) and isinstance(state.get('android'), dict),
                 'STAGE.json lacks the validated Android/sysbake record')
    for tool in ('bash', 'readelf'):
        core.require(shutil.which(tool), f'Missing host command: {tool}')
    safe_id(args.bundle_id, r'[A-Za-z0-9][A-Za-z0-9._-]*', 'bundle ID', core, 64)
    metadata, source, source_files = source_identity(root, core)
    core.require(args.bundle_id != metadata.get('bundle_id'),
                 'Choose a new --bundle-id; the source bundle ID belongs to the original release')
    args.tool_id = args.tool_id or 'lepton_custom_' + re.sub(r'[.-]', '_', args.bundle_id)
    safe_id(args.tool_id, r'[A-Za-z0-9_]+', 'tool ID', core, 96)
    core.require(args.tool_id != metadata.get('tool_id'), 'Choose a new --tool-id; the source tool ID belongs to the original release')
    if args.tool_name is not None:
        core.require(args.tool_name.strip() and not any(ord(c) < 32 or ord(c) == 127 for c in args.tool_name),
                     'Invalid tool name')
    output = Path(os.path.abspath(args.output_dir))
    core.require(output.parent.is_dir() and output.parent.resolve() == output.parent and not output.is_symlink(),
                 'Output directory parent must exist without symlinks')
    core.require(output != root and root not in output.parents, 'Bundle output must be outside the stage')
    name = f'lepton-x86_64-{args.bundle_id}'
    targets = [output / (name + suffix) for suffix in ('.tar.gz', '.install.sh', '.tar.gz.sha256')]
    for target in targets:
        core.require(not target.exists() and not target.is_symlink(), f'Output already exists; refusing overwrite: {target}')
    check_stage_for_package(root, state, core)
    components = check_components(root, state, core)
    # Version first, with the optional components: "lepton ID x86_64 (custom, GApps + NDK)".
    args.tool_name = args.tool_name or L.default_display_name(args.bundle_id, components, 'custom')
    print('Verifying the Android rootfs and sysbake against the stage record...', flush=True)
    rootfs_records, sysbake_records = stage_integrity(root, state, core)
    fingerprint = L.stage_fingerprint(root)['fingerprint']
    if state.get('runtime_fingerprint'):
        core.require(state['runtime_fingerprint'] == fingerprint, 'Runtime fingerprint inputs changed after validation')
    xattrs_sha = state['sysbake']['xattrs_sha256']
    sources = f'compat_tool/provenance/sources/{metadata.get("bundle_id")}'
    core.require(not (root / sources).exists(), f'Stage already carries provenance for {metadata.get("bundle_id")}')
    original = (source_files.get('BUNDLE-PROVENANCE.txt') or b'').decode('utf-8', 'replace')
    generated = {
        'BUNDLE.json': L.bundle_metadata(args.bundle_id, args.tool_id, args.tool_name, args.tool_id, components,
                                         origin='lepton-customize', source_bundle_id=metadata.get('bundle_id')).encode(),
        'STEAM-DECK-INSTALL.txt': L.install_text(args.tool_name, args.bundle_id, name + '.install.sh',
                                                 args.tool_id, args.tool_id).encode(),
        'tools/BUNDLE-PROVENANCE.txt': provenance_text(args, state, metadata, source, components,
                                                       (L.tree_digest(rootfs_records), L.tree_digest(sysbake_records),
                                                        xattrs_sha, fingerprint), original).encode(),
    }
    for file, data in source_files.items():
        generated[f'{sources}/{file}'] = data
    generated[f'{sources}/STAGE.json'] = (json.dumps(state, indent=2) + '\n').encode()
    if state.get('baked_from') == 'customized':
        image = root / 'tools/IMAGE-PROVENANCE.txt'
        if image.is_file():
            generated['tools/BASE-IMAGE-PROVENANCE.txt'] = image.read_bytes()
        generated['tools/IMAGE-PROVENANCE.txt'] = (
            'Customised Android rootfs: NOT compiled from a source checkout.\n'
            f'It is the base image of source bundle {metadata.get("bundle_id")} (tools/BASE-IMAGE-PROVENANCE.txt)\n'
            'with optional components added by lepton-customize inject (see compat_tool/provenance).\n').encode()
    legacy = root / 'tools/PROVENANCE.txt'
    if legacy.is_file():
        kept = [line for line in legacy.read_text(errors='replace').splitlines() if not line.startswith('Google ')]
        generated['tools/PROVENANCE.txt'] = ('\n'.join(kept + ['Google Android Platform-Tools adb: NOT included in this archive.']) + '\n').encode()
    for file in generated:
        core.require(core.canonical(file) == file, f'Unsafe generated path: {file}')

    entries = stage_entries(root, generated, core)
    size = sum((root / name).lstat().st_size for name in entries)
    for name in entries:
        core.require(not ADB_PATTERN.search(name) or name.startswith((L.ROOTFS, L.SYSBAKE)),
                     f'Refusing to package Google host adb: {name}')
    needed = size + sum(map(len, generated.values())) + 64 * 1024 * 1024
    core.require(shutil.disk_usage(output.parent if not output.exists() else output).free >= needed,
                 f'Insufficient disk space: need at least {needed // (1024 * 1024) + 1} MiB free')
    print(f'PASS: stage {state["state"]} validated; components: ' +
          ', '.join(f'{n}={str(components[n]).lower()}' for n in L.COMPONENTS), flush=True)
    if args.check:
        print(f'PASS: package preflight for {targets[0]}; nothing changed')
        return
    output.mkdir(exist_ok=True)
    work = Path(tempfile.mkdtemp(prefix='.lepton-package-', dir=output))
    published = []
    try:
        archive = work / targets[0].name
        print('Creating compressed archive (no rebuild; stage files as validated)...', flush=True)
        names = write_archive(root, archive, entries, generated)
        installer = work / targets[1].name
        template = (root / INSTALLER).read_text()
        installer.write_text(re.sub(r"^DEFAULT_ARCHIVE=''$", f"DEFAULT_ARCHIVE='{targets[0].name}'", template, count=1, flags=re.M))
        os.chmod(installer, 0o755)
        result = subprocess.run(['bash', '-n', str(installer)], capture_output=True, text=True)
        core.require(result.returncode == 0, 'Generated installer has a syntax error')
        print('Verifying the archive against the stage record...', flush=True)
        scan = checked(core, L.ArchiveScan, archive)
        core.require(scan.rootfs == rootfs_records, 'Archive Android rootfs differs from the validated stage')
        core.require(scan.sysbake == sysbake_records, 'Archive sysbake differs from the validated stage')
        core.require(L.file_sha256(root / L.XATTRS) == xattrs_sha and
                     scan.files.get(L.XATTRS) == (root / L.XATTRS).read_bytes(), 'Archive sysbake.xattrs differs')
        core.require(scan.fingerprint()['fingerprint'] == fingerprint, 'Archive runtime fingerprint inputs differ')
        core.require(scan.files.get('BUNDLE.json') == generated['BUNDLE.json'], 'Archive BUNDLE.json differs')
        listed = set(scan.other) | {L.ROOTFS + n for n in scan.rootfs} | {L.SYSBAKE + n for n in scan.sysbake}
        core.require(listed == names, 'Archive member list differs from the packaged stage')
        checksum = work / targets[2].name
        checksum.write_text(f'{scan.sha256}  {targets[0].name}\n{L.file_sha256(installer)}  {targets[1].name}\n')
        for source, target in zip((archive, installer, checksum), targets):
            core.publish(source, target)
            published.append(target)
    except BaseException:
        for target in published:
            target.unlink(missing_ok=True)
        raise
    finally:
        core.cleanup(work)
    for target in targets:
        print(f'PASS: {target}')
    print('This is a local customised bundle. It is unsigned and must not be presented as an official '
          'Google-free Lepton release.')
    if any(components.values()):
        print('It contains Google components from your own image: for personal use only.')


def write_archive(root, archive, entries, generated):
    names = set()
    with tarfile.open(archive, 'w:gz', compresslevel=1, format=tarfile.GNU_FORMAT) as tar:
        def normalise(info):
            info.uid = info.gid = 0
            info.uname = info.gname = ''
            return info
        top = tarfile.TarInfo('.')
        top.type, top.mode, top.mtime = tarfile.DIRTYPE, 0o755, int(time.time())
        tar.addfile(top)
        for name in entries:
            path = root / name
            info = normalise(tar.gettarinfo(str(path), './' + name))
            if info.isreg():
                with path.open('rb') as stream:
                    tar.addfile(info, stream)
            else:
                tar.addfile(info)
            names.add(name)
        for name, data in sorted(generated.items()):
            for parent in reversed(Path(name).parents):
                folder = parent.as_posix()
                if folder != '.' and folder not in names:
                    info = tarfile.TarInfo('./' + folder)
                    info.type, info.mode, info.mtime = tarfile.DIRTYPE, 0o755, int(time.time())
                    tar.addfile(info)
                    names.add(folder)
            info = tarfile.TarInfo('./' + name)
            info.size, info.mode, info.mtime = len(data), 0o644, int(time.time())
            tar.addfile(info, io.BytesIO(data))
            names.add(name)
    return names


